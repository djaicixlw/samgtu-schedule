/**
 * AUD-034: scripts/generate_group_chunks.ts — mojibake decoder, map coverage,
 * id unification and chunk generation from a ЛК export.
 *
 * Everything destructive (rename / map write) is exercised on TEMP copies or
 * via pure functions only — the work_src tree is never modified by this suite
 * (the batch diff must stay clean; renaming in the workspace is explicitly
 * out of scope for Батч D).
 */
import assert from 'node:assert';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const W = path.resolve(__dirname, '..');

let passed = 0;
function check(cond: any, label: string) {
  if (cond) { passed++; console.log(`  ✓ ${label}`); }
  else { console.error(`  ✗ FAIL ${label}`); process.exitCode = 1; }
}

const {
  decodeMojibakeName,
  scanSchedulesDir,
  chunkIdFromFileName,
  buildAutoMapEntries,
  renderAutoGeneratedSection,
  applyMapSection,
  generateChunkFromExport,
  DEFAULT_SCHEDULES_DIR,
  MAP_SECTION_BEGIN,
  MAP_SECTION_END
} = await import('../scripts/generate_group_chunks');
const { normalizeGroupId } = await import('../utils/groupAliases');
const { SAMGTU_GROUP_MAP } = await import('../utils/samgtuGroupMap');

console.log('\n--- 1. Mojibake decoder on real fixtures ---');
const fx1 = decodeMojibakeName('25РёРЅРіС‚-101Рј.json');
check(fx1.name === '25ингт-101м.json' && fx1.changed && fx1.confidence === 'high', `25РёРЅРіС‚-101Рј.json -> ${fx1.name}`);
const fx2 = decodeMojibakeName('26РёРЅРіС‚-104Рј.json');
check(fx2.name === '26ингт-104м.json' && fx2.confidence === 'high', '26-й intake decodes too');

// Already-correct names pass through untouched.
const fx3 = decodeMojibakeName('ingt-310.json');
check(fx3.name === 'ingt-310.json' && !fx3.changed, 'latin name untouched');
const fx4 = decodeMojibakeName('25ингт-101м.json');
check(fx4.name === '25ингт-101м.json' && !fx4.changed, 'correct cyrillic name untouched (idempotent)');

// Unknown pattern: mojibake chars present but decode does not yield a plausible name.
const fx5 = decodeMojibakeName('‚„…-.json');
check(!fx5.changed && fx5.confidence === 'none', 'unrecognized pattern -> confidence none, NOT renamed');

// A correct name that merely contains ё must not be "decoded" into garbage.
const fx6 = decodeMojibakeName('25ингт-ё101м.json');
check(fx6.confidence === 'none' || fx6.name === '25ингт-ё101м.json', 'ё in a correct name is not treated as decodable mojibake');

console.log('\n--- 2. Scan: coverage of the REAL schedules dir (no writes) ---');
const report = scanSchedulesDir(DEFAULT_SCHEDULES_DIR);
check(report.files.length === 64, `64 chunk files scanned (got ${report.files.length})`);
check(report.mojibake.length === 0, `real dir is canonical UTF-8 (post AUD-034 rename): 0 mojibake (got ${report.mojibake.length})`);
check(report.coveredInMap.length === 17, `hand-maintained map covers 17 (got ${report.coveredInMap.length})`);

// Lesson-id cross-check on a SYNTHETIC mojibake copy: the real dir was renamed
// to canonical UTF-8, but the decoder must still handle un-renamed repos.
// The JSON has no group field, but lesson id prefixes embed the decoded stem
// (`25ингт-101м-w1-tu-1`).
const tmpScanDir = fs.mkdtempSync(path.join(os.tmpdir(), 'aud034-scan-'));
fs.copyFileSync(
  path.join(DEFAULT_SCHEDULES_DIR, '25ингт-101м.json'),
  path.join(tmpScanDir, '25РёРЅРіС‚-101Рј.json'));
const scanReport = scanSchedulesDir(tmpScanDir);
check(scanReport.mojibake.length === 1, 'synthetic mojibake copy is detected (got ' + scanReport.mojibake.length + ')');
check(scanReport.mojibake[0].decoded.confidence === 'high', 'synthetic mojibake decodes with high confidence');
check(scanReport.mojibake[0].idPrefixMatch === 'yes', 'decoded stem confirmed by lesson-id prefixes inside the chunk');

console.log('\n--- 3. Auto map section covers every remaining chunk ---');
const autoEntries = buildAutoMapEntries(report);
const unionIds = new Set<string>([...Object.keys(SAMGTU_GROUP_MAP), ...Object.keys(autoEntries)]);
const everyFileCovered = report.files.every(f => unionIds.has(f.groupId));
check(everyFileCovered, 'map ∪ AUTO-GENERATED covers ALL local chunks');
check(Object.keys(autoEntries).length === report.notInMap.length, 'one auto entry per unmapped chunk');
check(Object.values(autoEntries).every(e => e.samgtuGroupId === 0), 'portal ids are 0 (unknown) — NOT guessed');
check(Object.values(autoEntries).every(e => isValidLike(e.name)), 'auto names are valid display names');
function isValidLike(name: string): boolean { return typeof name === 'string' && name.length > 0 && !/[РС][ёіїЅјђ]/.test(name); }

console.log('\n--- 4. Ids resolve uniformly through normalizeGroupId ---');
for (const gid of Object.keys(autoEntries)) {
  if (normalizeGroupId(gid) !== gid) {
    check(false, `auto id ${gid} is not a fixpoint of normalizeGroupId`);
  }
}
check(true, 'all auto ids are normalizeGroupId fixpoints');
check(chunkIdFromFileName('25ингт-101м.json') === '25ingt-101m', 'chunkIdFromFileName canonicalizes (25ингт-101м -> 25ingt-101m)');
check(chunkIdFromFileName('ingt-310.json') === 'ingt-310', 'latin stems are their own fixpoint');

console.log('\n--- 5. renderAutoGeneratedSection + applyMapSection (temp copy) ---');
const section = renderAutoGeneratedSection(autoEntries, '2026-10-25');
check(section.startsWith(MAP_SECTION_BEGIN) && section.endsWith(MAP_SECTION_END), 'section is delimited by markers');
check(section.includes('2026-10-25'), 'section carries the generation date');
check(section.includes('samgtuGroupId: 0'), 'section documents unknown portal ids');

const mapPath = path.join(W, 'utils', 'samgtuGroupMap.ts');
const originalMapTs = fs.readFileSync(mapPath, 'utf8');
const once = applyMapSection(originalMapTs, section);
check((once.match(new RegExp(MAP_SECTION_BEGIN.replace(/[()]/g, '\\$&'), 'g')) || []).length === 1, 'section inserted once');
check(once.includes("'ingt-301'"), 'original hand-maintained entries preserved');
const twice = applyMapSection(once, renderAutoGeneratedSection(autoEntries, '2026-10-26'));
check(!twice.includes('2026-10-25') && twice.includes('2026-10-26'), 'second apply REPLACES the section (idempotent)');
check((twice.match(new RegExp(MAP_SECTION_END.replace(/[()]/g, '\\$&'), 'g')) || []).length === 1, 'still exactly one section after re-run');

console.log('\n--- 6. --rename mode on a TEMP copy seeded with mojibake fixtures ---');
// The real dir is canonical (AUD-034 rename applied), so the temp copy is
// seeded by DE-canonicalizing two files back into their mojibake names.
const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'aud034-rename-'));
for (const f of fs.readdirSync(DEFAULT_SCHEDULES_DIR).filter(f => f.endsWith('.json'))) {
  fs.copyFileSync(path.join(DEFAULT_SCHEDULES_DIR, f), path.join(tmpDir, f));
}
fs.renameSync(path.join(tmpDir, '25ингт-101м.json'), path.join(tmpDir, '25РёРЅРіС‚-101Рј.json'));
fs.renameSync(path.join(tmpDir, '26ингт-104м.json'), path.join(tmpDir, '26РёРЅРіС‚-104Рј.json'));
const realListingBefore = fs.readdirSync(DEFAULT_SCHEDULES_DIR).filter(f => f.endsWith('.json')).sort();
check(fs.readdirSync(tmpDir).includes('25РёРЅРіС‚-101Рј.json'), 'temp dir contains the seeded mojibake file');

const { execFileSync } = await import('node:child_process');
const npxCmd = process.platform === 'win32' ? 'npx.cmd' : 'npx';
execFileSync(npxCmd, ['tsx', 'scripts/generate_group_chunks.ts', '--dir', tmpDir, '--rename', '--report', path.join(tmpDir, '..', 'report.txt')], {
  cwd: W, stdio: 'pipe', shell: process.platform === 'win32'
});
const afterRename = fs.readdirSync(tmpDir).filter(f => f.endsWith('.json')).sort();
check(!afterRename.includes('25РёРЅРіС‚-101Рј.json') && !afterRename.includes('26РёРЅРіС‚-104Рј.json'), 'mojibake files renamed in temp dir');
check(afterRename.includes('25ингт-101м.json') && afterRename.includes('26ингт-104м.json'), 'decoded names present in temp dir');
check(afterRename.length === 64, 'file count unchanged by rename (got ' + afterRename.length + ')');
const realListingAfter = fs.readdirSync(DEFAULT_SCHEDULES_DIR).filter(f => f.endsWith('.json')).sort();
check(JSON.stringify(realListingBefore) === JSON.stringify(realListingAfter), 'REAL work_src dir untouched by the test');
fs.rmSync(tmpDir, { recursive: true, force: true });

console.log('\n--- 7. Chunk generation from a ЛК export (parser reuse, no network) ---');
const html = fs.readFileSync(path.join(W, 'tests', 'user_lk_export.html'), 'utf8');
const gen = generateChunkFromExport(html, { groupNameOverride: '25ингт-101м' });
check(gen.ok === true, 'chunk generation succeeds from the ЛК HTML fixture');
check(gen.groupId === '25ingt-101m', `groupId via makeGroupId (got ${gen.groupId})`);
check(gen.lessonCount! > 0, `chunk non-empty (${gen.lessonCount} lessons)`);
// scheduleSchema contract: validateWeekData accepts the produced weeks as-is.
const { validateWeekData } = await import('../utils/scheduleSchema');
const validation = validateWeekData(gen.weeks);
check(validation.ok === true, 'generated weeks pass validateWeekData (scheduleSchema contract)');
const weekKeys = Object.keys(gen.weeks as object).sort();
check(weekKeys.join(',') === '1,2,3,4', 'chunk carries weeks 1..4');

// Round-trip: the generated file name equals the id the app requests.
check(`${gen.groupId}.json` === '25ingt-101m.json', 'chunk file name == canonical id');

// Bad id -> refused, not guessed.
const badGen = generateChunkFromExport('<html><body>no group info</body></html>');
check(badGen.ok === false && badGen.reason === 'bad-group-id', 'generation refuses to invent a group id');

console.log('\n--- 8. nightly_sync skips AUTO-GENERATED entries (portal id 0) ---');
const syncSrc = fs.readFileSync(path.join(W, 'scripts', 'nightly_sync.ts'), 'utf8');
check(syncSrc.includes('if (!conf.samgtuGroupId)'), 'nightly_sync guards against samgtuGroupId=0');

console.log(`\n[${passed} checks passed]`);
if (process.exitCode !== 1) console.log('=== AUD-034 GROUP CHUNKS SUITE PASSED ===');
